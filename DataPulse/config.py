class DataValidationRules:
    """Класс с правилами валидации входных данных.
    
    Содержит требования к CSV файлам, допустимые диапазоны значений
    и формат обязательных колонок.
    """
    
    # Обязательные колонки, которые должны присутствовать в CSV файле
    REQUIRED_COLUMNS = ['date', 'quantity', 'price']
    
    # Допустимый диапазон дат для анализа
    DATE_RANGE = {
        'min': datetime(2000, 1, 1),  # Минимальная дата (с 1 января 2000 года)
        'max': datetime(2030, 12, 31)  # Максимальная дата (до 31 декабря 2030 года)
    }
    
    # Допустимые диапазоны значений для числовых колонок
    VALUE_RANGES = {
        'quantity': (0, 1000000),  # Количество товара: от 0 до 1,000,000 единиц
        'price': (0, 10000000),  # Цена товара: от 0 до 10,000,000 рублей
        'total_sales': (0, 100000000)  # Общая выручка: от 0 до 100,000,000 рублей
    }